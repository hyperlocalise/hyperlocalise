#!/usr/bin/env node
/**
 * Regenerates apps/go-svc/workspace-identity-profanity-en.txt from the
 * @2toad/profanity package installed in apps/hyperlocalise-web.
 *
 * Usage:
 *   node scripts/generate-workspace-profanity-list.mjs [--check]
 */

import { createHash } from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WEB_REQUIRE = createRequire(path.join(ROOT, "apps/hyperlocalise-web/package.json"));
const OUTPUT = path.join(ROOT, "apps/go-svc/workspace-identity-profanity-en.txt");

export function renderProfanityList() {
  const packageDir = path.dirname(WEB_REQUIRE.resolve("@2toad/profanity/package.json"));
  const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, "package.json"), "utf8"));
  const license = fs.readFileSync(path.join(packageDir, "LICENSE"), "utf8").trim();
  const { profaneWords } = WEB_REQUIRE(path.join(packageDir, "dist/data"));
  const words = profaneWords.get("en");
  for (const word of words) {
    if (word.startsWith("#") || /[\r\n]/.test(word) || word !== word.trim()) {
      throw new Error(`unsupported word list entry: ${JSON.stringify(word)}`);
    }
  }
  const digest = createHash("sha256").update(words.join("\n")).digest("hex");
  const header = [
    `Generated by scripts/generate-workspace-profanity-list.mjs. Do not edit.`,
    `Source: ${pkg.name}@${pkg.version} dist/data/profane-words.js, language "en".`,
    `Words: ${words.length}; sha256(words joined by LF): ${digest}`,
    "",
    ...license.split("\n"),
  ].map((line) => (line ? `# ${line}` : "#"));
  return `${[...header, ...words].join("\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderProfanityList();
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(OUTPUT, "utf8") !== rendered) {
      console.error(`${path.relative(ROOT, OUTPUT)} is stale; rerun without --check`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, rendered);
  }
}
