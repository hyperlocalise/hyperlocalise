export function slugifySanityPathSegment(name: string, fallbackId: string): string {
  const base = name.trim() || fallbackId.replace(/^drafts\./, "");
  const slug = base
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
  return slug.length > 0 ? slug : "doc";
}
